// language; entries that need numbers or names are functions: t('key', value).
// Kannada needs a review by a fluent speaker before release.
const KEY = 'jaldrishti.lang'

let lang = 'en'
try {
  if (localStorage.getItem(KEY) === 'kn') lang = 'kn'
} catch {
  // storage blocked: stay in English
}
document.documentElement.lang = lang

export const getLang = () => lang
export function setLang(next) {
  lang = next
  document.documentElement.lang = next
  try {
    localStorage.setItem(KEY, next)
  } catch {
    // not remembered, still switches
  }
}

